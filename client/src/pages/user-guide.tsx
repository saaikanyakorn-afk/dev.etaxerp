interface AiChatMessage {
  role: "user" | "assistant";
  content: string;
}

function AiGuideChat() {
  const [open, setOpen] = useState(false);
  const [input, setInput] = useState("");
  const [messages, setMessages] = useState<AiChatMessage[]>([]);
  const scrollRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const askMutation = useMutation({
    mutationFn: async (question: string) => {
      const res = await fetch("/api/ai/user-guide", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        credentials: "include",
        body: JSON.stringify({ question, history: messages.slice(-10) }),
      });
      if (!res.ok) {
        const err = await res.json().catch(() => ({ message: "เกิดข้อผิดพลาด" }));
        throw new Error(err.message);
      }
      return res.json();
    },
    onSuccess: (data) => {
      setMessages((prev) => [...prev, { role: "assistant", content: data.answer }]);
    },
    onError: (err: Error) => {
      setMessages((prev) => [...prev, { role: "assistant", content: `ขออภัย: ${err.message}` }]);
    },
  });

  const handleSend = () => {
    const q = input.trim();
    if (!q || askMutation.isPending) return;
    setMessages((prev) => [...prev, { role: "user", content: q }]);
    setInput("");
    askMutation.mutate(q);
  };

  useEffect(() => {
    if (scrollRef.current) {
      scrollRef.current.scrollTop = scrollRef.current.scrollHeight;
    }
  }, [messages, askMutation.isPending]);

  useEffect(() => {
    if (open && inputRef.current) inputRef.current.focus();
  }, [open]);

  if (!open) {
    return (
      <button
        onClick={() => setOpen(true)}
        className="fixed bottom-6 right-6 z-50 flex items-center gap-2 px-4 py-3 rounded-full shadow-lg text-white font-medium hover:scale-105 transition-transform no-print"
        style={{ background: "linear-gradient(135deg, #fb9678 0%, #f94d4d 100%)" }}
        data-testid="button-open-ai-guide"
        title="ถาม AI ผู้ช่วย"
      >
        <Sparkles className="h-5 w-5" />
        <span className="text-sm">ถาม AI ผู้ช่วย</span>
      </button>
    );
  }

  return (
    <div className="fixed bottom-6 right-6 z-50 w-[380px] max-h-[520px] flex flex-col rounded-2xl shadow-2xl border border-border bg-card overflow-hidden no-print" data-testid="ai-guide-chat">
      <div className="flex items-center justify-between px-4 py-3 text-white" style={{ background: "linear-gradient(135deg, #fb9678 0%, #f94d4d 100%)" }}>
        <div className="flex items-center gap-2">
          <Bot className="h-5 w-5" />
          <span className="font-semibold text-sm">E-Tax Assistant</span>
        </div>
        <button onClick={() => setOpen(false)} className="rounded-full p-1 hover:bg-white/20 transition-colors" data-testid="button-close-ai-guide">
          <X className="h-4 w-4" />
        </button>
      </div>

      <div ref={scrollRef} className="flex-1 overflow-y-auto p-3 space-y-3 min-h-[300px] max-h-[380px]">
        {messages.length === 0 && (
          <div className="text-center py-8 space-y-3">
            <div className="mx-auto w-12 h-12 rounded-full flex items-center justify-center" style={{ background: "#fb967820" }}>
              <Sparkles className="h-6 w-6" style={{ color: "#fb9678" }} />
            </div>
            <div>
              <p className="font-semibold text-foreground text-sm">สวัสดีค่ะ! ฉันคือ E-Tax Assistant</p>
              <p className="text-xs text-muted-foreground mt-1">ถามวิธีใช้งานโปรแกรมได้เลยค่ะ</p>
            </div>
            <div className="space-y-1.5">
              {[
                "สร้างใบเสนอราคายังไง?",
                "วิธีเพิ่มพนักงานใหม่",
                "เงินสดย่อยใช้งานยังไง?",
              ].map((q) => (
                <button
                  key={q}
                  onClick={() => {
                    setMessages([{ role: "user", content: q }]);
                    askMutation.mutate(q);
                  }}
                  className="block w-full text-left text-xs px-3 py-2 rounded-lg border border-border hover:bg-muted/50 transition-colors text-muted-foreground hover:text-foreground"
                  data-testid={`button-suggest-${q.slice(0, 10)}`}
                >
                  {q}
                </button>
              ))}
            </div>
          </div>
        )}

        {messages.map((msg, i) => (
          <div key={i} className={`flex ${msg.role === "user" ? "justify-end" : "justify-start"}`}>
            <div
              className={`max-w-[85%] rounded-2xl px-3 py-2 text-sm leading-relaxed whitespace-pre-wrap ${
                msg.role === "user"
                  ? "bg-[#fb9678] text-white rounded-br-md"
                  : "bg-muted text-foreground rounded-bl-md"
              }`}
            >
              {msg.content}
            </div>
          </div>
        ))}

        {askMutation.isPending && (
          <div className="flex justify-start">
            <div className="bg-muted rounded-2xl rounded-bl-md px-3 py-2 flex items-center gap-2">
              <Loader2 className="h-4 w-4 animate-spin text-muted-foreground" />
              <span className="text-xs text-muted-foreground">กำลังคิด...</span>
            </div>
          </div>
        )}
      </div>

      <div className="border-t border-border p-2 flex gap-2">
        <Input
          ref={inputRef}
          value={input}
          onChange={(e) => setInput(e.target.value)}
          onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); handleSend(); } }}
          placeholder="พิมพ์คำถาม..."
          className="flex-1 h-9 text-sm"
          disabled={askMutation.isPending}
          data-testid="input-ai-guide-question"
        />
        <Button
          size="sm"
          className="h-9 w-9 p-0 text-white"
          style={{ background: "#fb9678" }}
          disabled={!input.trim() || askMutation.isPending}
          onClick={handleSend}
          data-testid="button-send-ai-guide"
        >
          <Send className="h-4 w-4" />
        </Button>
      </div>
    </div>
  );
}

